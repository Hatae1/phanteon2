export const getLocalizedEntityName = (name: string, isEn: boolean): string => {
  if (!isEn || !name) return name;

  if (ENTITY_NAME_MAP[name]) {
    return ENTITY_NAME_MAP[name];
  }

  // Clean trailing annotations like "(헤라)", "(티탄)" etc.
  let cleaned = name;
  for (const [ko, en] of Object.entries(ENTITY_NAME_MAP)) {
    if (cleaned.includes(ko)) {
      cleaned = cleaned.replace(ko, en);
    }
  }

  return cleaned;
};

