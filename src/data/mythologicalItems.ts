export function filterItems(
  items: MythologicalItem[],
  category: ItemCategory,
  searchQuery: string
): MythologicalItem[] {
  return items.filter(item => {
    // Category filter
    if (category !== 'all' && item.category !== category) {
      return false;
    }

    // Search query filter
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase().trim();
      const matchName = item.nameKo.toLowerCase().includes(q);
      const matchEn = item.nameEn.toLowerCase().includes(q);
      const matchGreek = item.nameGreek.toLowerCase().includes(q);
      const matchOwner = item.owner.toLowerCase().includes(q);
      const matchCreator = item.creator.toLowerCase().includes(q);
      const matchSummary = item.summary.toLowerCase().includes(q);
      const matchSubType = item.subType.toLowerCase().includes(q);

      if (
        !matchName &&
        !matchEn &&
        !matchGreek &&
        !matchOwner &&
        !matchCreator &&
        !matchSummary &&
        !matchSubType
      ) {
        return false;
      }
    }

    return true;
  });
}
